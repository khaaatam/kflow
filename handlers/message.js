const fs = require('fs');
const path = require('path');
const config = require('../config');
const db = require('../lib/database');
const logger = require('../lib/logger');
const eventBus = require('../lib/eventBus');
const { COMMAND_COOLDOWN_MS, OBSERVER_DEBOUNCE_MS, AI_RATE_WINDOW_MS, AI_RATE_MAX, MEMORY_LIST_LIMIT, CHAT_HISTORY_LIMIT } = require('../lib/constants');
const RateLimiter = require('../lib/rateLimiter');
const Memory = require('../models/Memory');
const ChatLog = require('../models/ChatLog');
const model = require('../lib/ai');
const react = require('../lib/react');
const { sendVoiceNote } = require('../lib/tts');

// --- Human-like behavior config ---
const TYPING_DELAY_MIN_MS = 1000;
const TYPING_DELAY_MAX_MS = 3000;
const VOICE_REPLY_CHANCE = 0.25; // 25% chance to reply with voice
const AUTO_REACT_CHANCE = 0.3;  // 30% chance to auto-react
const AUTO_REACT_EMOJI = ['❤️', '😍', '🥰', '😘', '💕', '✨', '😊', '💗', '🔥', '💐'];

// --- Relationship features: only for Dini ---
const DINI_IDS = ['6283806618448@c.us', '129428856242227@lid', '6283806618448@lid'];

function isDini(senderId) {
    return DINI_IDS.includes(senderId);
}

function randomDelay(min, max) {
    return Math.floor(min + Math.random() * (max - min));
}

async function humanLikeDelay(client, msg) {
    if (!msg.fromMe && !msg.isGroup && isDini(msg.from)) {
        try {
            await client.pupPage.evaluate((chatId) => {
                window.Store?.Chat?.find(chatId)?.then(chat => chat?.sendSeen()); // eslint-disable-line no-undef
            }, msg.from);
        } catch { /* best-effort */ }

        try {
            await client.sendPresenceAvailable();
            await new Promise(r => setTimeout(r, randomDelay(TYPING_DELAY_MIN_MS, TYPING_DELAY_MAX_MS)));
            await client.sendPresenceUnavailable();
        } catch { /* best-effort */ }
    }
}

async function autoReact(msg) {
    if (msg.fromMe || msg.isGroup || !isDini(msg.from)) return;
    if (Math.random() > AUTO_REACT_CHANCE) return;
    const emoji = AUTO_REACT_EMOJI[Math.floor(Math.random() * AUTO_REACT_EMOJI.length)];
    await react(msg, emoji);
}

const mentionLimiter = new RateLimiter(AI_RATE_WINDOW_MS, AI_RATE_MAX);

// Bot name variants for mention detection (lowercase)
const BOT_MENTIONS = ['bot', 'jikaelbot', 'jikael'];

// ============================================================
// 🔄 PRE-LOAD COMMANDS (SEKALIGUS SCAN PUBLIC COMMAND)
// ============================================================
const commands = new Map();
const publicCommands = [];

const commandFiles = fs.readdirSync(path.join(__dirname, '../commands')).filter(file => file.endsWith('.js'));

for (const file of commandFiles) {
    try {
        const module = require(`../commands/${file}`);
        if (module.metadata && module.metadata.commands) {
            module.metadata.commands.forEach(cmd => {
                const handler = module.interact || module;
                commands.set(cmd.command, handler);

                if (cmd.isPublic) {
                    publicCommands.push(cmd.command.toLowerCase());
                }
            });
        }
    } catch (e) { logger.error(`Skip ${file}: ${e.message}`); }
}
logger.info(`${commands.size} Commands Loaded!`);

const cooldowns = new Map();
const observerCooldowns = new Map();

// ============================================================
// PIPELINE STAGES
// ============================================================

function filterStatus(_ctx, msg) {
    if (msg.isStatus || msg.type === 'e2e_notification' || msg.type === 'call_log') return false;
}

function parseContext(ctx, msg) {
    const body = msg.body || '';
    let rawSenderId = msg.author || msg.from;

    if (msg.fromMe && ctx.client.info && ctx.client.info.wid) {
        rawSenderId = ctx.client.info.wid._serialized;
    }

    let senderId = rawSenderId;
    if (senderId.includes(':')) {
        senderId = senderId.substring(0, senderId.indexOf(':')) + senderId.substring(senderId.indexOf('@'));
    }

    const isGroup = msg.from.includes('@g.us');
    let namaPengirim = config.users[senderId];
    const isRegisteredUser = !!namaPengirim;
    if (!namaPengirim) namaPengirim = msg.pushName || 'Guest';

    const cleanBody = body.trim();
    const isBotResponse = msg.fromMe && (
        /^\p{Extended_Pictographic}/u.test(cleanBody) ||
        cleanBody.includes('[DEBUG]') ||
        cleanBody.includes('SYSTEM ONLINE') ||
        cleanBody.includes('Generated by') ||
        cleanBody.includes('[MEMORY SAVED]')
    );

    const isPublicCommand = publicCommands.some(cmd => body.toLowerCase().startsWith(cmd));
    const isLink = body.match(/(https?:\/\/[^\s]+)/g);
    const isDownloaderLink = isLink && (
        body.toLowerCase().includes('tiktok.com') ||
        body.toLowerCase().includes('facebook.com') ||
        body.toLowerCase().includes('instagram.com')
    );

    ctx.body = body;
    ctx.rawSenderId = rawSenderId;
    ctx.senderId = senderId;
    ctx.isGroup = isGroup;
    ctx.namaPengirim = namaPengirim;
    ctx.isRegisteredUser = isRegisteredUser;
    ctx.cleanBody = cleanBody;
    ctx.isBotResponse = isBotResponse;
    ctx.isPublicCommand = isPublicCommand;
    ctx.isDownloaderLink = isDownloaderLink;
}

function filterBotResponse(ctx) {
    if (ctx.isBotResponse) return false;
}

function logMessage(ctx, msg) {
    if (!ctx.isGroup && ctx.cleanBody.length > 0) {
        db.query(
            'INSERT INTO full_chat_logs (nama_pengirim, pesan, is_forwarded) VALUES (?, ?, ?)',
            [ctx.namaPengirim, msg.body, msg.isForwarded ? 1 : 0]
        ).catch((e) => logger.error('Chat log insert failed:', e.message));

        logger.info(`[${ctx.namaPengirim}]: ${msg.body}`);
    }
}

function filterGuest(ctx) {
    if (!ctx.isRegisteredUser && !ctx.isPublicCommand && !ctx.isDownloaderLink) {
        logger.debug(`[GUEST DROP] ID: ${ctx.senderId} | Nama: ${ctx.namaPengirim}`);
        return false;
    }
}

async function handleCommand(ctx, client, msg) {
    if (ctx.body.startsWith('!') || ctx.body.startsWith('/')) {
        const args = ctx.body.trim().split(/ +/);
        const commandName = args[0].toLowerCase();

        if (commands.has(commandName)) {
            if (cooldowns.has(ctx.rawSenderId)) {
                if (Date.now() < cooldowns.get(ctx.rawSenderId) + COMMAND_COOLDOWN_MS) return false;
            }

            const handler = commands.get(commandName);
            try {
                await handler(client, msg, args, ctx.rawSenderId, ctx.namaPengirim, ctx.body);
            } catch (e) {
                logger.error(`Cmd Error [${commandName}]: ${e.message}`);
            }

            // Track usage (fire-and-forget)
            db.query(
                'INSERT INTO command_usage (command, user_name, is_group) VALUES (?, ?, ?)',
                [commandName, ctx.namaPengirim, ctx.isGroup ? 1 : 0]
            ).catch(() => {});

            cooldowns.set(ctx.rawSenderId, Date.now());
            setTimeout(() => cooldowns.delete(ctx.rawSenderId), COMMAND_COOLDOWN_MS);
            return false;
        }
    }
}

async function handleAutoDownload(ctx, client, msg) {
    if (ctx.isDownloaderLink) {
        if (msg.hasMedia || ctx.isGroup) return;

        const autoHandler = commands.get('(auto detect)') || commands.get('(Auto Detect)');
        if (autoHandler) {
            logger.info('Link Download Terdeteksi!');
            await autoHandler(client, msg, [], ctx.rawSenderId, ctx.namaPengirim, ctx.body);
            return false;
        }
    }
}

function handleObserver(ctx, client, msg) {
    if (!ctx.body.startsWith('!') && !ctx.body.startsWith('/') && !ctx.isGroup && ctx.isRegisteredUser) {
        const lastObserve = observerCooldowns.get(ctx.rawSenderId) || 0;
        if (Date.now() - lastObserve > OBSERVER_DEBOUNCE_MS) {
            observerCooldowns.set(ctx.rawSenderId, Date.now());
            setTimeout(() => observerCooldowns.delete(ctx.rawSenderId), OBSERVER_DEBOUNCE_MS);
            eventBus.emit('message:incoming', { client, msg, namaPengirim: ctx.namaPengirim });
        }
    }
}

// ============================================================
// MENTION TRIGGER — @bot <message> di group chat
// ============================================================
async function handleMention(ctx, client, msg) {
    if (!ctx.isGroup) return;

    const bodyLower = ctx.body.toLowerCase();

    // Cek apakah ada mention ke bot (@bot, @jikaelbot, @jikael)
    let mentioned = false;
    let query = '';

    for (const mention of BOT_MENTIONS) {
        const pattern = `@${mention}`;
        const idx = bodyLower.indexOf(pattern);
        if (idx !== -1) {
            mentioned = true;
            // Ambil teks setelah mention
            query = ctx.body.slice(idx + pattern.length).trim();
            break;
        }
    }

    if (!mentioned) return;

    // Gak ada pesan setelah mention
    if (!query) {
        await msg.reply('Halo! Ada yang bisa gw bantu?');
        return false;
    }

    // Rate limit
    if (!mentionLimiter.check(ctx.rawSenderId)) {
        await msg.reply('⏳ Terlalu banyak request. Tunggu sebentar.');
        return false;
    }

    await react(msg, '👀');

    try {
        const persona = await Memory.getPersona();
        const memories = await Memory.getByUser(ctx.namaPengirim, MEMORY_LIST_LIMIT);
        const chatHistory = await ChatLog.getHistoryByUser(ctx.namaPengirim, CHAT_HISTORY_LIMIT);
        const memText = memories.map(m => `- ${m.fakta}`).join('\n');
        const today = new Date().toLocaleDateString('id-ID', { weekday: 'long', year: 'numeric', month: 'long', day: 'numeric' });

        const systemMessage = `[INSTRUKSI SISTEM]
Kamu adalah: ${persona}
Tanggal hari ini: ${today}
User yang sedang bicara denganmu: ${ctx.namaPengirim} (di group chat)

[INGATAN TENTANG USER INI]
${memText || '(Belum ada ingatan)'}

[ATURAN PERILAKU]
- Balas dengan natural dalam Bahasa Indonesia, sesuaikan dengan persona.
- Gunakan ingatan untuk merespons secara personal.
- Jaga agar balasan tetap singkat (1-2 kalimat).
- Kamu sedang di group chat, jadi jangan terlalu panjang.`;

        const userMessage = `[CHAT TERAKHIR]
${chatHistory || '(Belum ada chat history)'}

User (${ctx.namaPengirim}): "${query}"`;

        const payload = [
            { role: 'system', content: systemMessage },
            { role: 'user', content: userMessage }
        ];

        const result = await model.generateContent(payload);
        let reply = result.response.text().replace(/^(Bot|AI):/i, '').trim();

        if (result.fallback) {
            reply = result.response.text();
        } else {
            reply += '\n\n_Generated by ' + (config.botName || 'AI') + '_';
        }

        await react(msg, '✅');

        // Voice reply: 25% chance (only for Dini)
        if (isDini(msg.from) && Math.random() < VOICE_REPLY_CHANCE && reply.length > 0 && reply.length < 200) {
            const cleanReply = reply.replace(/_Generated by .+_/g, '').trim();
            const sent = await sendVoiceNote(client, msg.from, cleanReply, msg.id._serialized);
            if (!sent) await msg.reply(reply);
        } else {
            await msg.reply(reply);
        }

    } catch (e) {
        logger.error('Mention AI Error:', e);
        await msg.reply('❌ AI lagi error.');
    }

    return false;
}

// ============================================================
// MAIN HANDLER (PIPELINE)
// ============================================================
const messageHandler = async (client, msg) => {
    try {
        const ctx = { client };

        const stages = [
            () => filterStatus(ctx, msg),
            () => parseContext(ctx, msg),
            () => filterBotResponse(ctx),
            () => logMessage(ctx, msg),
            () => autoReact(msg),
            () => humanLikeDelay(client, msg),
            () => filterGuest(ctx),
            (c) => handleCommand(c, client, msg),
            (c) => handleAutoDownload(c, client, msg),
            (c) => handleMention(c, client, msg),
            (c) => handleObserver(c, client, msg),
        ];

        for (const stage of stages) {
            const result = await stage(ctx);
            if (result === false) return;
        }
    } catch (error) {
        logger.error('Handler Fatal Error:', error.message);
    }
};

module.exports = messageHandler;
module.exports.commands = commands;
